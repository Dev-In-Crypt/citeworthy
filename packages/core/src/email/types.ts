/**
 * Почта продукта: приглашения в агентство и восстановление пароля.
 *
 * Транспорт спрятан за интерфейсом по тем же причинам, что и платформы:
 * отправка писем — внешний вызов с деньгами, лимитами и отказами, а тесты
 * в сеть не ходят. Базовая реализация ничего не отправляет и складывает
 * письма в память, поэтому продукт полностью работает без ключей.
 */

export interface EmailMessage {
  to: string;
  subject: string;
  /** Текстовая версия обязательна: письмо должно читаться и без HTML. */
  text: string;
  html?: string;
  /**
   * Имя отправителя вместо имени продукта. Адрес остаётся тем, что
   * подтверждён у транспорта; меняется только то, что видит получатель в
   * поле «От». Для писем клиентам агентства — название агентства (инвариант 3).
   */
  fromName?: string;
}

export interface SentEmail {
  /** Идентификатор письма у транспорта — для разбора «дошло или нет». */
  id: string;
}

export interface EmailSender {
  send(message: EmailMessage): Promise<SentEmail>;
}
